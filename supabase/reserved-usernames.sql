-- *[demo] reserved usernames. Run once in Supabase: SQL Editor -> New query -> paste -> Run. Safe to run again.
--
-- Keeps well-known artists' and songwriters' names (and the app's own words like admin, support, official)
-- from being taken by someone else. Nobody owns them: they're simply unavailable until you hand one to
-- the real person once you've checked it's them.
--
-- Matching ignores capitals and underscores, and for artists' names also catches the usual impersonation dress-up:
-- real/thereal/official/its/iam in front, or official/music/hq/vevo/tv/fans/daily/news on the end.
-- So with "taylorswift" reserved, taylor_swift, therealtaylorswift and taylorswiftofficial are all refused.
--
-- Only usernames being set or changed are checked: anyone who already has one keeps it (the last query
-- in this file lists any that clash, so you can look at them).
--
-- Hand a name to its owner (after verifying them), by the email they signed in with:
--   select public.grant_username('taylorswift', 'their@email.com');
-- Add one:      insert into public.reserved_usernames (key, kind, note) values (public.username_key('Some Name'), 'artist', 'Some Name');
-- Release one:  delete from public.reserved_usernames where key = public.username_key('Some Name');

create table if not exists public.reserved_usernames (
  key         text primary key,
  kind        text not null default 'artist' check (kind in ('artist','system')),
  note        text,
  granted_to  uuid references auth.users(id) on delete set null,
  created_at  timestamptz not null default now()
);
-- locked away from the app entirely: no policies, so only the dashboard (and the check below) can read it
alter table public.reserved_usernames enable row level security;

create or replace function public.username_key(name text)
returns text language sql immutable as $$
  select regexp_replace(lower(coalesce(name, '')), '[^a-z0-9]', '', 'g')
$$;

-- every form a username could be "wearing": as typed, without a real/official prefix, without a suffix, without both
create or replace function public.username_forms(name text)
returns text[] language sql immutable as $$
  with k as (select public.username_key(name) as a),
       p as (select a, regexp_replace(a, '^(thereal|real|official|its|iam)', '') as b from k)
  select array[a, b,
               regexp_replace(a, '(official|music|hq|vevo|tv|fans|fan|daily|news)$', ''),
               regexp_replace(b, '(official|music|hq|vevo|tv|fans|fan|daily|news)$', '')] from p
$$;

create or replace function public.profiles_reserved_guard()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.username is not null
     and (tg_op = 'INSERT' or new.username is distinct from old.username)
     and exists (select 1 from public.reserved_usernames r
                 where (r.key = public.username_key(new.username)
                        or (r.kind = 'artist' and r.key = any(public.username_forms(new.username))))
                   and r.key <> ''
                   and (r.granted_to is null or r.granted_to is distinct from new.user_id)) then
    raise exception 'reserved_username: That username is reserved.' using errcode = 'P0001';
  end if;
  return new;
end $$;
drop trigger if exists profiles_reserved_guard on public.profiles;
create trigger profiles_reserved_guard before insert or update on public.profiles
  for each row execute function public.profiles_reserved_guard();

create or replace function public.grant_username(name text, email text)
returns text language plpgsql security definer set search_path = public as $$
declare who uuid; k text := public.username_key(name);
begin
  select id into who from auth.users u where lower(u.email) = lower(grant_username.email) limit 1;
  if who is null then return 'No account signs in with ' || email || ' yet. Ask them to sign in to the app once, then run this again.'; end if;
  insert into public.reserved_usernames (key, kind, note, granted_to) values (k, 'artist', name, who)
    on conflict (key) do update set granted_to = excluded.granted_to;
  return 'Done: ' || email || ' can now choose @' || k || ' in Account.';
end $$;
-- for the dashboard only, never the app
revoke all on function public.grant_username(text, text) from public, anon, authenticated;

